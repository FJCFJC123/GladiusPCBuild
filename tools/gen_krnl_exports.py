"""Generate gladiusport.dll's krnl_* exports (the converted exe imports one per former kernel thunk slot).

  forwards  : the only kernel functions app code calls directly (critical sections) -> src/critsec.cpp,
              which implements them on the Xbox 28-byte layout (often statically initialized in .data)
  data      : kernel data exports -> zeroed placeholder blocks
  functions : traps that report the import name and the caller (a missed XAPI/D3D/DSOUND replacement)
"""
import os
HERE = os.path.dirname(__file__)
from kernel_names import KERNEL_IMPORTS as names

# implemented in src/*.cpp (critsec.cpp, krnl_time.cpp): direct kernel calls made by app code / CRT
FORWARD = {'RtlInitializeCriticalSection', 'RtlEnterCriticalSection', 'RtlLeaveCriticalSection',
           'RtlTryEnterCriticalSection', 'KeQuerySystemTime', 'RtlTimeToTimeFields', 'RtlTimeFieldsToTime',
           'RtlNtStatusToDosError'}
DATA = {'ExEventObjectType', 'ExSemaphoreObjectType', 'ExMutantObjectType', 'ExTimerObjectType',
        'XePublicKeyData', 'LaunchDataPage', 'XboxHardwareInfo', 'XboxKrnlVersion', 'PsThreadObjectType',
        'KeTimeIncrement', 'XeImageFileName', 'HalDiskCachePartitionCount', 'IdexChannelObject',
        'NtUserIoApcDispatcher', 'IoFileObjectType', 'XboxHDKey', 'XboxSignatureKey',
        'XboxAlternateSignatureKeys', 'KeTickCount', 'HalBootSMCVideoMode'}
# (RtlCompareMemory, RtlFillMemoryUlong, DbgBreakPoint, IoInvalidDeviceRequest are functions - Ghidra labels them data)
assert FORWARD <= set(names) and DATA <= set(names)

src = ['// GENERATED by tools/gen_krnl_exports.py - do not edit.',
       '// One export per former Xbox kernel import slot of the converted exe.',
       '#include "port.h"', '',
       'static const char *const k_names[] = {']
src += [f'    "{n}",' for n in names] + ['};', '']
for n in names:
    if n in DATA:
        src.append(f'extern "C" __declspec(align(16)) unsigned char krnl_{n}[256] = {{0}};')
src.append('')
for i, n in enumerate(names):
    if n not in FORWARD and n not in DATA:
        src.append(f'extern "C" __declspec(naked) void krnl_{n}() {{ __asm push {i} __asm jmp port_kernel_trap }}')
src.append('')
src.append('const char *krnl_name(int i) { return i >= 0 && i < %d ? k_names[i] : "?"; }' % len(names))
open(os.path.join(HERE, '..', 'src', 'krnl_exports.cpp'), 'w').write('\n'.join(src) + '\n')

defs = ['LIBRARY gladiusport', 'EXPORTS', '    port_start']
for n in names:
    if n in FORWARD:
        defs.append(f'    krnl_{n}')
    elif n in DATA:
        defs.append(f'    krnl_{n} DATA')
    else:
        defs.append(f'    krnl_{n}')
from replacements import REPLACE, D3D_FASTCALL
defs += [f'    {name}=@{name}@{D3D_FASTCALL[name]}' if name in D3D_FASTCALL else f'    {name}'
         for addr, name, argb, note in REPLACE]
open(os.path.join(HERE, '..', 'src', 'gladiusport.def'), 'w').write('\n'.join(defs) + '\n')
print(len(names), 'exports:', len(FORWARD), 'implemented,', len(DATA), 'data,', len(names) - len(FORWARD) - len(DATA), 'traps')
