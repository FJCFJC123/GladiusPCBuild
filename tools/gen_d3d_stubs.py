"""Generate logging stubs for every Xbox library entry the game calls that is not yet implemented by hand:
  src/d3d_stubs.cpp     (tools/d3d_table.entries, hand-written versions in src/d3d_*.cpp)
  src/dsound_stubs.cpp  (tools/d3d_table.dsound_entries, hand-written versions in src/dsound_*.cpp)
A stub reports its first call with arguments (port.log), counts calls, and returns 0 with the exact calling
convention, so the game keeps running and every first use of an unimplemented function is visible.
"""
import os, re, glob
from d3d_table import entries, dsound_entries

HERE = os.path.dirname(__file__)
SRC = os.path.join(HERE, '..', 'src')


def implemented(prefix):
    names = set()
    for f in glob.glob(os.path.join(SRC, prefix + '_*.cpp')):
        if f.endswith('_stubs.cpp'):
            continue
        names |= set(re.findall(r'\b' + prefix + r'_(\w+)\s*\(', open(f).read()))
    return names


def generate(prefix, header, table, stub_fn):
    done = implemented(prefix)
    out = [f'// GENERATED by tools/gen_d3d_stubs.py - do not edit. Hand-written versions live in src/{prefix}_*.cpp.',
           f'#include "{header}"', '']
    for addr, name, conv, nstack, regs in table:
        if name in done:
            continue
        params = [f'DWORD {r}' for r in regs] + [f'DWORD a{i}' for i in range(nstack)]
        cc = '__fastcall' if conv == 'fastcall' else '__stdcall'
        if conv == 'fastcall' and len(regs) < 2:            # keep MSVC fastcall register assignment exact
            params = ['DWORD ecx', 'DWORD edx'] + [f'DWORD a{i}' for i in range(nstack)]
        args = ', '.join(p.split()[1] for p in params)
        fmt = ' '.join(['%08X'] * len(params))
        out.append(f'extern "C" DWORD {cc} {prefix}_{name}({", ".join(params) or "void"})')
        out.append('{')
        out.append(f'    {stub_fn}(0x{addr:06X}, "{name}", "{fmt}"{", " if params else ""}{args});')
        out.append('    return 0;')
        out.append('}')
    open(os.path.join(SRC, prefix + '_stubs.cpp'), 'w').write('\n'.join(out) + '\n')
    n, k = len(table), len(done & {e[1] for e in table})
    print(f'{prefix}: {n} entries, {k} hand-written, {n - k} stubs')


def main():
    generate('d3d', 'd3d.h', entries(), 'd3d_stub_call')
    generate('dsound', 'dsound.h', dsound_entries(), 'dsound_stub_call')


if __name__ == '__main__':
    main()
